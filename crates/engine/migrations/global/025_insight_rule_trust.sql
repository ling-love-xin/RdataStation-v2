-- 025: 洞察「项目规则信任」记录（信任门，架构 §12 Q1 ③）
--
-- 背景：项目层规则落在 `{项目}/.RSmeta/insight-rules/`，**跟着仓库走**。
-- 于是「克隆一个不信任的仓库 + 打开项目」就等于把它的 SQL 拿到本机执行；
-- 解析期静态门（D52）只挡「不是只读查询」的写法，挡不住一条合法但恶意的查询。
-- 真正的边界是**人的一次决定**：这个项目的规则要不要加载。
--
-- 为什么存在**全局库**而不是项目库：项目目录在被信任之前就是不可信输入——
-- 信任标记如果写在项目里，攻击者可以连标记一起提交（自我授权）。全局库在
-- 用户的数据根下，项目文件碰不到。
--
-- 语义（fail closed）：
--   * 无记录            → 未信任：项目层规则不装配、不参与任何分析（但索引照常扫描，
--                         用户要看得见「带了什么」才好做决定）
--   * state = 'trusted' → 装配项目层
--   * state = 'declined'→ 不装配；**同时记录这次决定**，避免每次打开项目都追问
--
-- 已知取舍：信任绑定**项目路径**，不是规则内容。项目里的规则后来被改动
-- （例如 git pull 带进来一条新规则）不会重新确认——否则用户自己改规则也会被反复打扰。
-- 要更严的口径，需要在这里再加一列内容指纹（见架构 §12 Q1 的「更严一档」）。
--
-- 幂等：CREATE TABLE IF NOT EXISTS，迁移按版本号只执行一次。

CREATE TABLE IF NOT EXISTS insight_rule_trust (
    project_path TEXT PRIMARY KEY,                       -- 规范化后的项目根路径
    state        TEXT NOT NULL CHECK (state IN ('trusted', 'declined')),
    decided_at   TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
