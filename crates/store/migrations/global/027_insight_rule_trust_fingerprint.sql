-- 027: 洞察「项目规则信任」补内容指纹列（信任门补强，架构 §12 Q1「更严一档」落地）
--
-- 背景（025 的已知取舍）：信任原本绑定**项目路径**——项目里的规则后来被改动
-- （例如 git pull 带进来一条新规则）不会重新确认。代价是「已信任的项目被
-- 注入新 SQL」这条路径完全敞开。
--
-- 本列把决定绑定到**决定时的规则集内容**（指纹 = 按 (相对路径, 文件 SHA256)
-- 排序聚合的 SHA256，见 `insight::service::rule_trust::ruleset_fingerprint`）：
--   * 用户做出决定（信任 / 拒绝）时写入此刻的指纹；
--   * 读取时：state = 'trusted' 且指纹与磁盘现状不符 → 按未决定处理
--     （fail closed，不回写本表；用户重新确认时覆盖新指纹）；
--   * 指纹为 NULL（027 之前决定的旧记录）：按纯路径语义放行——升级当天不让
--     全体存量用户回到未确认，用户下一次做出决定起绑定内容；
--   * 决定时规则集为空：存空串（''）而不是 NULL——「信任了空规则集、随后
--     出现规则文件」同样要重新确认（NULL 严格保留给「旧记录未绑定」）。
--
-- 代价（有意接受）：用户自己改规则也会触发重新确认——信任的对象是
-- 「这份内容」，不是「这个目录」。规则开发者的顺手的替代路径：把规则放
-- 全局层（{系统目录}/insight-rules/，随本机而不随项目，无信任门）。
--
-- 幂等：迁移按版本号只执行一次；SQLite 的 ALTER TABLE ADD COLUMN 无 IF NOT EXISTS。

ALTER TABLE insight_rule_trust ADD COLUMN fingerprint TEXT;
